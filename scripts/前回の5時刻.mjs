#!/usr/bin/env node
// 前回の 5 時刻の算出 — 前回の確定シフトの行から、日ごとの 5 時刻を出す。
//
//   使い方: node scripts/前回の5時刻.mjs
//   宣言:   scripts/前回の5時刻の宣言.json（算出の規則も期待値も食い違いの読みもあちらが持つ。このファイルに書かない）
//
// 5 時刻（準備開始／調理開始／調理終了／片付け開始／片付け終了）は、入力の行としては記録に無い。
// だが確定シフトの 171 行を日と役割で束ねると、帯が読める（→ docs/tech-requirements.md 7）。
// ここが出すのは、その算出した値と、どの行から出たかである。
//
// M2 の判定（scripts/M2の判定.mjs）と生成の所要時間の実測（scripts/生成の所要時間.mjs）が、
// 条件入力の「日ごとの営業時刻」としてこの値を読む。値を宣言に焼かない — 焼くと、data が動いても気づけない。
// 宣言が持つのは算出の規則と、data が動いたことに気づくための期待値である。
//
// M1 ① は別の置き方のままである（1 日を 1 本の帯として刻む → scripts/M1①の宣言.json）。
// M1 ① が見るのは型に乗るかだけで、帯の内訳を見ないので、変える理由が無い。
//
// 何も書き換えない。読むだけである。期待値を外すか、確かめることを 1 つでも落としたら終了コード 1 で落ちる。

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ここ = path.dirname(fileURLToPath(import.meta.url))
const 根 = path.dirname(ここ)
const 読む = (相対) => fs.readFileSync(path.join(根, 相対), 'utf8')

const 宣言 = JSON.parse(読む('scripts/前回の5時刻の宣言.json'))

/** 5 時刻の並び。条件入力の「日ごとの営業時刻」の列の順そのものである（→ 5-1 の #1）。 */
export const 時刻の名 = ['準備開始', '調理開始', '調理終了', '片付け開始', '片付け終了']

/** 帯の名と、その端に当たる時刻（→ 5-5・src/generate.js の prepCleanupBands）。 */
const 帯 = [
  { 名: '準備', 始: '準備開始', 終: '調理開始' },
  { 名: '調理', 始: '調理開始', 終: '調理終了' },
  { 名: '片付け', 始: '片付け開始', 終: '片付け終了' },
]

const 枠の分 = 30

const 分に = (時刻) => Number(String(時刻).slice(0, 2)) * 60 + Number(String(時刻).slice(3, 5))

/** 確定シフトの 4 本を、日で束ねられる 1 本の行の列にする。ファイルの割れ方では束ねない（→ 宣言の「入力」）。 */
function 確定シフトの行() {
  const 行 = []
  宣言.入力.確定シフト.forEach((相対) => {
    JSON.parse(読む(相対)).results.forEach((一人) => {
      (一人.assigned || []).forEach((一つ) => {
        行.push({ 在処: 相対, 日: 一つ.date, 始: 一つ.start, 終: 一つ.end, 役割: 一つ.role })
      })
    })
  })
  return 行
}

/** 行の中で最も早い始端（無ければ null）。どの行から出たかも返す。 */
function 最も早い始端(行) {
  if (行.length === 0) return null
  return 行.slice().sort((甲, 乙) => 分に(甲.始) - 分に(乙.始))[0]
}

/** 行の中で最も遅い終端（無ければ null）。どの行から出たかも返す。 */
function 最も遅い終端(行) {
  if (行.length === 0) return null
  return 行.slice().sort((甲, 乙) => 分に(乙.終) - 分に(甲.終))[0]
}

/** 出どころ 1 つ分 — どの値が、どの日の何行のうちのどの行から出たか。 */
function 出どころ(値, 何行から, 行, どう取ったか) {
  return {
    値: 値,
    どう取ったか: どう取ったか,
    何行から: 何行から,
    どの行から: 行 === null ? null : `${行.在処} の ${行.日} ${行.始}-${行.終} ${行.役割}`,
  }
}

/**
 * 1 日ぶんの 5 時刻を算出する（→ 宣言の「算出の規則」）。
 *
 * 準備開始 ＝ その日の最も早い始端 ／ 片付け終了 ＝ その日の最も遅い終端。
 * 調理開始 ＝ 準備 の行の最も遅い終端（準備の行が無い日は 準備開始 に寄せる）。
 * 片付け開始 ＝ 片付け の行の最も早い始端（片付けの行が無い日は 片付け終了 に寄せる）。
 * 調理終了 ＝ 片付け開始（記録に間を示す行が 1 つも無いので、間を作らない）。
 *
 * 役割名は文字どおり読む。2025-11-04 の 11 行が全部 準備 であることも、そのまま読む（→ 宣言の「決め」）。
 */
function 一日の5時刻(日, 行) {
  const 準備の行 = 行.filter((一つ) => 一つ.役割 === '準備')
  const 片付けの行 = 行.filter((一つ) => 一つ.役割 === '片付け')

  const 最早 = 最も早い始端(行)
  const 最遅 = 最も遅い終端(行)
  const 準備の終わり = 最も遅い終端(準備の行)
  const 片付けの始まり = 最も早い始端(片付けの行)

  const 準備開始 = 最早.始
  const 片付け終了 = 最遅.終
  const 調理開始 = 準備の終わり === null ? 準備開始 : 準備の終わり.終
  const 片付け開始 = 片付けの始まり === null ? 片付け終了 : 片付けの始まり.始
  const 調理終了 = 片付け開始

  return {
    日: 日,
    時刻: [準備開始, 調理開始, 調理終了, 片付け開始, 片付け終了],
    行数: 行.length,
    出どころ: [
      出どころ(準備開始, 行.length, 最早, 'その日の全行のうち最も早い start'),
      出どころ(
        調理開始, 準備の行.length, 準備の終わり,
        準備の終わり === null ? '準備 の行が 1 つも無いので 準備開始 に寄せた（準備帯 0 枠）' : '役割が 準備 の行のうち最も遅い end',
      ),
      出どころ(調理終了, 片付けの行.length, 片付けの始まり, '片付け開始 と同じ値（記録に間を示す行が無い）'),
      出どころ(
        片付け開始, 片付けの行.length, 片付けの始まり,
        片付けの始まり === null ? '片付け の行が 1 つも無いので 片付け終了 に寄せた（片付け帯 0 枠）' : '役割が 片付け の行のうち最も早い start',
      ),
      出どころ(片付け終了, 行.length, 最遅, 'その日の全行のうち最も遅い end'),
    ],
  }
}

/** その日の枠と、帯ごとの枠数。刻み方は src/input-types.js の cutSlots と同じである（→ 5-1 の #1）。 */
function 帯ごとの枠(時刻) {
  const 値 = {}
  時刻の名.forEach((名, at) => { 値[名] = 時刻[at] })

  let 全枠 = 0
  const 帯の枠 = {}
  帯.forEach((一つ) => {
    const 終わり = 分に(値[一つ.終])
    let 数 = 0
    for (let 始 = 分に(値[一つ.始]); 始 + 枠の分 <= 終わり; 始 += 枠の分) 数 += 1
    帯の枠[一つ.名] = 数
    全枠 += 数
  })
  return { 全枠: 全枠, 帯の枠: 帯の枠 }
}

/**
 * 前回の確定シフトから、日ごとの 5 時刻を算出する。
 *
 * 返すのは日の順（日付の昇順）の配列である。1 日 1 件で、出どころも持つ。
 * 読むだけで、data も宣言も書き換えない。
 */
export function 前回の5時刻() {
  const 行 = 確定シフトの行()
  const 日々 = []
  行.forEach((一つ) => { if (日々.indexOf(一つ.日) === -1) 日々.push(一つ.日) })
  日々.sort()

  return 日々.map((日) => {
    const 一日 = 一日の5時刻(日, 行.filter((一つ) => 一つ.日 === 日))
    const 枠 = 帯ごとの枠(一日.時刻)
    return Object.assign(一日, 枠)
  })
}

/**
 * 条件入力の「日ごとの営業時刻」の行にする（[日付, 5 時刻...]）。
 * M2 の判定と生成の所要時間の実測が、これをそのまま型 #1 に通す。
 */
export function 営業時刻の行() {
  return 前回の5時刻().map((一日) => [一日.日].concat(一日.時刻))
}

/**
 * 算出した値を検める — 宣言の期待値との突き合わせと、「確かめること」の合否。
 *
 * 読む側（M2 の判定 ／ 生成の所要時間の実測）が、入力を見るところでこれを呼ぶ。
 * 件数や秒より先に、入力に使う 5 時刻が期待どおりかを見るためである。
 * 検めそのものの原本はこの手と宣言で、呼ぶ側は結果を出すだけである。
 */
export function 検める() {
  const 算出 = 前回の5時刻()
  const 突き合わせ = 期待値と突き合わせる(算出)
  const 見た = 確かめる(算出)
  return {
    算出: 算出,
    外れ: 突き合わせ.外れ,
    枠: 突き合わせ.枠,
    確かめた: 見た,
    落ちた: 突き合わせ.外れ.length !== 0 || 見た.some((一つ) => !一つ.合否),
    ここが外れたら: 宣言.算出した値の期待値.ここが外れたら,
  }
}

// ---- 検める側（検める() と、単体で走らせたときの主処理が使う） ----------------

/** 算出した値が、宣言の期待値と同じか。外れたら data か規則が動いたということである。 */
function 期待値と突き合わせる(算出) {
  const 期待 = 宣言.算出した値の期待値
  const 外れ = []

  const 算出した日 = 算出.map((一日) => 一日.日)
  const 期待の日 = Object.keys(期待['日ごとの 5 時刻']).filter((鍵) => /^\d{4}-\d{2}-\d{2}$/.test(鍵))
  if (JSON.stringify(算出した日) !== JSON.stringify(期待の日)) {
    外れ.push(`日の並び: ${JSON.stringify(算出した日)}（期待 ${JSON.stringify(期待の日)}）`)
  }

  算出.forEach((一日) => {
    const 期待の時刻 = 期待['日ごとの 5 時刻'][一日.日]
    if (期待の時刻 && JSON.stringify(一日.時刻) !== JSON.stringify(期待の時刻)) {
      外れ.push(`${一日.日} の 5 時刻: ${JSON.stringify(一日.時刻)}（期待 ${JSON.stringify(期待の時刻)}）`)
    }
    if (期待['日ごとの枠'][一日.日] !== undefined && 一日.全枠 !== 期待['日ごとの枠'][一日.日]) {
      外れ.push(`${一日.日} の枠: ${一日.全枠}（期待 ${期待['日ごとの枠'][一日.日]}）`)
    }
    const 期待の帯 = 期待['日ごとの帯の枠'][一日.日]
    if (期待の帯 && JSON.stringify(一日.帯の枠) !== JSON.stringify(期待の帯)) {
      外れ.push(`${一日.日} の帯の枠: ${JSON.stringify(一日.帯の枠)}（期待 ${JSON.stringify(期待の帯)}）`)
    }
  })

  const 枠 = 算出.reduce((合計, 一日) => 合計 + 一日.全枠, 0)
  if (枠 !== 期待.枠) 外れ.push(`枠の通し: ${枠}（期待 ${期待.枠}）`)

  return { 外れ: 外れ, 枠: 枠 }
}

/** 宣言の「確かめること」を 1 つずつ見る。落ちた理由を名指しで返す。 */
function 確かめる(算出) {
  const 見た = []

  const 乗らない時刻 = []
  算出.forEach((一日) => {
    一日.時刻.forEach((時刻, at) => {
      if (分に(時刻) % 枠の分 !== 0) 乗らない時刻.push(`${一日.日} の ${時刻の名[at]} ${時刻}`)
    })
  })
  見た.push({ 何: '5 時刻がどれも 30 分に乗っている', 合否: 乗らない時刻.length === 0, 内訳: 乗らない時刻.join(' / ') || '4 日 × 5 時刻とも :00 か :30 である' })

  const 逆順 = []
  算出.forEach((一日) => {
    for (let i = 1; i < 一日.時刻.length; i++) {
      if (分に(一日.時刻[i - 1]) <= 分に(一日.時刻[i])) continue
      逆順.push(`${一日.日} の ${時刻の名[i - 1]} ${一日.時刻[i - 1]} が ${時刻の名[i]} ${一日.時刻[i]} より後`)
    }
  })
  見た.push({ 何: '5 時刻が早い順に並んでいる', 合否: 逆順.length === 0, 内訳: 逆順.join(' / ') || '4 日とも早い順である' })

  const 学祭2日 = 算出.filter((一日) => 帯.every((一つ) => 一日.帯の枠[一つ.名] > 0))
  const 帯が欠けた日 = 算出
    .filter((一日) => 帯.some((一つ) => 一日.帯の枠[一つ.名] === 0))
    .map((一日) => `${一日.日}（${帯.filter((一つ) => 一日.帯の枠[一つ.名] === 0).map((一つ) => 一つ.名).join('・')} が 0 枠）`)
  見た.push({
    何: '準備帯・調理帯・片付け帯がどれも 1 枠以上ある日が 2 日ある（学祭 2 日 → 規則 3 の ②〜⑤ が測れる）',
    合否: 学祭2日.length >= 2,
    内訳: `3 帯とも立っている日: ${学祭2日.map((一日) => 一日.日).join(' / ') || '無い'}`
      + `${帯が欠けた日.length === 0 ? '' : ` ／ 帯が 0 枠の日: ${帯が欠けた日.join(' / ')}（→ 宣言の決め）`}`,
  })

  return 見た
}

/** 4-2 の説明文の営業時間 ◎ と、算出した片付け終了が揃っているか。揃わなくても止まらない（→ 宣言）。 */
function 営業時間と突き合わせる(算出) {
  const 営業時間 = 宣言.確かめること.filter((一つ) => 一つ['4-2 の営業時間'])[0]['4-2 の営業時間']
  return 算出.map((一日) => ({
    日: 一日.日,
    片付け終了: 一日.時刻[4],
    '4-2': 営業時間[一日.日],
    揃った: 営業時間[一日.日] === 一日.時刻[4],
  }))
}

function 主処理() {
  const 検め = 検める()
  const 算出 = 検め.算出
  const 見た = 検め.確かめた
  const 営業時間 = 営業時間と突き合わせる(算出)
  const 本文 = 読む(宣言.本文.ファイル)
  const 本文に無い言葉 = 宣言.本文.載っているはずの言葉.filter((言葉) => 本文.indexOf(言葉) === -1)

  console.log('')
  console.log('前回の 5 時刻の算出 — 前回の確定シフトの行から、日ごとの 5 時刻を出す')
  console.log('')
  console.log(`何のための手か: ${宣言.何のための手か}`)
  console.log(`M1 ① との違い: ${宣言['M1 ① は別の置き方である']}`)
  console.log('')
  console.log('入力（読むのは 4 つの項目だけである）')
  console.log(`  ${宣言.入力.確定シフト.join(' / ')}`)
  console.log(`  ${宣言.入力.読む項目}`)

  console.log('')
  console.log('算出の規則（原本は scripts/前回の5時刻の宣言.json）')
  宣言.算出の規則.forEach((一つ) => {
    console.log(`  ・${一つ.何}: ${一つ.どう取るか}`)
    console.log(`      なぜ: ${一つ.なぜ}`)
  })

  console.log('')
  console.log('決め（記録の食い違いをどう読むか。記録そのものは 1 文字も書き換えない）')
  宣言.決め.forEach((一つ) => {
    console.log(`  ・${一つ.何}`)
    console.log(`      ${一つ.決め}`)
    console.log(`      なぜ: ${一つ.なぜこちらを採ったか || 一つ.なぜ埋めないか}`)
  })

  console.log('')
  console.log('算出した 5 時刻（値の出どころを、どの行から出たかまで出す）')
  算出.forEach((一日) => {
    console.log(`  ${一日.日}  ${一日.時刻.join(' ')}  … その日 ${一日.行数} 行から`)
    一日.出どころ.forEach((一つ, at) => {
      console.log(`      ${時刻の名[at].padEnd(5, '　')} ${一つ.値}  ← ${一つ.どう取ったか}`)
      console.log(`               ${一つ.どの行から === null ? '（当たる行が 1 つも無い）' : 一つ.どの行から}`)
    })
  })

  console.log('')
  console.log('刻んだ枠と帯（枠の刻み方は src/input-types.js の cutSlots と同じである）')
  算出.forEach((一日) => {
    const 帯の内訳 = 帯.map((一つ) => `${一つ.名} ${一日.帯の枠[一つ.名]}`).join(' ／ ')
    console.log(`  ${一日.日}  全 ${一日.全枠} 枠 = ${帯の内訳}`)
  })
  console.log(`  通し        ${検め.枠} 枠`)

  console.log('')
  console.log('期待値との突き合わせ（原本は data/ の行である。期待値は data が動いたことに気づくための見張りである）')
  if (検め.外れ.length === 0) {
    console.log('  OK   算出した値が、宣言の期待値と 1 つも違わない')
  } else {
    検め.外れ.forEach((一つ) => console.log(`  NG   ${一つ}`))
    console.log(`       ${宣言.算出した値の期待値.ここが外れたら}`)
  }

  console.log('')
  console.log('確かめること（原本は scripts/前回の5時刻の宣言.json）')
  見た.forEach((一つ) => {
    console.log(`  ${一つ.合否 ? 'OK ' : 'NG '}  ${一つ.何}`)
    console.log(`       ${一つ.内訳}`)
  })

  console.log('')
  console.log('4-2 の説明文の営業時間 ◎ との突き合わせ（別々の記録が日の終わりで揃っているか。揃わなくても止まらない）')
  営業時間.forEach((一つ) => {
    console.log(`  ${一つ.揃った ? 'OK ' : '-- '}  ${一つ.日}  片付け終了 ${一つ.片付け終了} ／ 4-2 の営業時間 ${一つ['4-2']}`)
  })

  console.log('')
  console.log('本文（宣言が写した言葉が載っているかだけを見る。本文は解析しない）')
  if (本文に無い言葉.length === 0) {
    console.log(`  OK   ${宣言.本文.載っているはずの言葉.join(' / ')} は ${宣言.本文.ファイル} に載っている`)
  } else {
    本文に無い言葉.forEach((言葉) => console.log(`  NG   ${宣言.本文.ファイル} に載っていない: ${言葉}`))
  }

  const 落ちた = 検め.落ちた || 本文に無い言葉.length !== 0

  if (落ちた) {
    console.log('')
    console.log(`次に何を動かすか — ${宣言.値が動いたら.この手が決めないこと}`)
    宣言.値が動いたら.分かれ道.forEach((枝) => {
      console.log(`  ・${枝.疑う先}: ${枝.どういうときか}`)
      console.log(`      動かす先: ${枝.動かす先}`)
    })
  }

  console.log('')
  console.log(
    `結果: ${算出.map((一日) => `${一日.日} ${一日.時刻.join(' ')}`).join(' ／ ')}`,
  )
  console.log(`      枠 ${検め.枠}（${算出.map((一日) => 一日.全枠).join('/')}）`)
  console.log('')

  return 落ちた ? 1 : 0
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(主処理())
}
